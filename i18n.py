"""
English / Arabic strings.

    tr(lang, "err.not_held")                 -> text in `lang`
    tr(lang, "msg.hero_name_set", name="X")  -> with {placeholders} filled

Key prefixes:  err.* errors   msg.* plain messages   emb.* embed text
               lbl.* labels / placeholders / modal titles

Rules: an unknown language falls back to English; an unknown key returns the
key itself (so a typo is visible, never a crash); a missing {placeholder} is
left as-is. Canonical show phrases ("Tikki, Spots On!") are NOT translated.
"""

DEFAULT_LANG = "en"
LANGUAGES = ("en", "ar")


class _Safe(dict):
    def __missing__(self, key):
        return "{" + key + "}"


def tr(lang: str, key: str, **kw) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    text = entry.get(lang) or entry[DEFAULT_LANG]
    if kw:
        try:
            return text.format_map(_Safe(kw))
        except (ValueError, IndexError):
            return text
    return text


def _s(en: str, ar: str) -> dict:
    return {"en": en, "ar": ar}


